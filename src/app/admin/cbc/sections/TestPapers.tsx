"use client";

import { useMemo, useState } from "react";
import type { SectionProps } from "../CbcApp";
import type {
  NewTestPaper,
  PaperDifficulty,
  PaperKind,
  QuestionType,
  StudyMaterial,
  TestPaper,
} from "@/lib/cbc/types";
import { PAPER_DIFFICULTIES, PAPER_KINDS, QUESTION_TYPES } from "@/lib/cbc/types";
import { CURRICULUM_SEED } from "@/lib/cbc/curriculum-seed";
import { MAX_MATERIAL_CHARS, MIN_MATERIAL_CHARS } from "@/lib/cbc/papers";
import {
  CbcBadge,
  CbcButton,
  CbcEmpty,
  CbcField,
  CbcInput,
  CbcNotice,
  CbcSelect,
  CbcTextarea,
} from "../ui";
import {
  SectionHeader,
  areaName,
  areasForGrade,
  classLabel,
  fmtDate,
  gradeLabel,
} from "./common";

/**
 * Test Papers — draft an assessment from the teacher's own study material.
 *
 * The paper is generated by the AI provider configured on the server and is
 * never saved implicitly: the teacher reviews it, can fix the marking guides,
 * then saves it. Printing always produces the learner copy (marking guides are
 * screen-only), so a paper can be handed out without leaking answers.
 */

const TYPE_LABEL: Record<QuestionType, string> = Object.fromEntries(
  QUESTION_TYPES.map((t) => [t.id, t.label]),
) as Record<QuestionType, string>;

const KIND_LABEL: Record<PaperKind, string> = Object.fromEntries(
  PAPER_KINDS.map((k) => [k.id, k.label]),
) as Record<PaperKind, string>;

const DIFFICULTY_LABEL: Record<PaperDifficulty, string> = Object.fromEntries(
  PAPER_DIFFICULTIES.map((d) => [d.id, d.label]),
) as Record<PaperDifficulty, string>;

/** A saved paper minus the fields the store owns — what the form edits. */
function toDraft(p: TestPaper): NewTestPaper {
  return {
    title: p.title,
    kind: p.kind,
    gradeId: p.gradeId,
    classId: p.classId,
    learningAreaId: p.learningAreaId,
    termId: p.termId,
    durationMins: p.durationMins,
    difficulty: p.difficulty,
    instructions: p.instructions,
    questions: p.questions,
    totalMarks: p.totalMarks,
    materialTitle: p.materialTitle,
    model: p.model,
    ...(p.materialId ? { materialId: p.materialId } : {}),
  };
}

interface PaperGroup {
  type: QuestionType;
  questions: TestPaper["questions"];
}

function groupQuestions(questions: TestPaper["questions"]): PaperGroup[] {
  const groups: PaperGroup[] = [];
  for (const q of questions) {
    const last = groups[groups.length - 1];
    if (last && last.type === q.type) last.questions.push(q);
    else groups.push({ type: q.type, questions: [q] });
  }
  return groups;
}

interface PaperForm {
  materialTitle: string;
  notes: string;
  reuseId: string;
  classId: string;
  /** "" until a grade is chosen (or derived from the selected class). */
  gradeId: string;
  learningAreaId: string;
  kind: PaperKind;
  title: string;
  topic: string;
  durationMins: number;
  totalMarks: number;
  questionCount: number;
  difficulty: PaperDifficulty;
  types: QuestionType[];
}

export function TestPapersSection({ ctx }: SectionProps) {
  const { data, activeYearId, activeTermId, saveRecord, deleteRecord, me } = ctx;

  const classes = useMemo(
    () => data.classes.filter((c) => c.yearId === activeYearId && c.active),
    [data.classes, activeYearId],
  );
  const first = classes[0];

  const [form, setForm] = useState<PaperForm>({
    materialTitle: "",
    notes: "",
    reuseId: "",
    classId: first?.id ?? "",
    gradeId: first?.gradeId ?? "",
    learningAreaId: "",
    kind: "test" as PaperKind,
    title: "",
    topic: "",
    durationMins: 40,
    totalMarks: 40,
    questionCount: 10,
    difficulty: "balanced" as PaperDifficulty,
    types: ["mcq", "short", "structured"] as QuestionType[],
  });

  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [needsConfig, setNeedsConfig] = useState(false);
  const [warnings, setWarnings] = useState<string[]>([]);
  const [paper, setPaper] = useState<NewTestPaper | null>(null);
  const [savedId, setSavedId] = useState<string | null>(null);
  const [dirty, setDirty] = useState(false);
  const [showAnswers, setShowAnswers] = useState(false);
  const [saving, setSaving] = useState(false);
  const [notice, setNotice] = useState<{ kind: "ok" | "err"; text: string } | null>(null);

  const areas = form.gradeId ? areasForGrade(form.gradeId) : [];
  const classesSorted = [...classes].sort((a, b) => a.name.localeCompare(b.name));

  const savedPapers = useMemo(
    () => [...data.papers].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)),
    [data.papers],
  );
  const savedMaterials = useMemo(
    () => [...data.materials].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt)),
    [data.materials],
  );

  /* --------------------------------- actions -------------------------------- */

  function setClass(id: string) {
    const cls = classes.find((c) => c.id === id);
    setForm((f) => ({ ...f, classId: id, gradeId: cls?.gradeId ?? "", learningAreaId: "" }));
  }

  function setGrade(id: string) {
    // Picking a grade directly means the paper is not tied to one class.
    setForm((f) => ({ ...f, gradeId: id, classId: "", learningAreaId: "" }));
  }

  function toggleType(t: QuestionType) {
    setForm((f) => ({
      ...f,
      types: f.types.includes(t) ? f.types.filter((x) => x !== t) : [...f.types, t],
    }));
  }

  function validate(): string | null {
    if (!form.gradeId) return "Choose the grade this paper is for.";
    if (!form.learningAreaId) return "Choose the learning area the paper covers.";
    const length = form.notes.trim().length;
    if (length < MIN_MATERIAL_CHARS) {
      return `Paste at least ${MIN_MATERIAL_CHARS} characters of study material — the paper is written only from your notes (you have ${length}).`;
    }
    if (length > MAX_MATERIAL_CHARS) {
      return `Study material is too long — maximum ${MAX_MATERIAL_CHARS} characters. Trim it or split it into two papers.`;
    }
    if (!form.types.length) return "Choose at least one question type.";
    if (form.questionCount < 3 || form.questionCount > 40)
      return "Question count must be between 3 and 40.";
    if (form.totalMarks < 10 || form.totalMarks > 200)
      return "Total marks must be between 10 and 200.";
    return null;
  }

  async function generate(e: React.FormEvent) {
    e.preventDefault();
    const problem = validate();
    if (problem) {
      setError(problem);
      return;
    }
    setBusy(true);
    setError(null);
    setNeedsConfig(false);
    setWarnings([]);
    setNotice(null);
    try {
      const res = await fetch("/api/cbc/test-paper", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          material: { title: form.materialTitle, notes: form.notes },
          options: {
            title: form.title,
            kind: form.kind,
            gradeId: form.gradeId,
            classId: form.classId,
            learningAreaId: form.learningAreaId,
            termId: activeTermId,
            durationMins: form.durationMins,
            totalMarks: form.totalMarks,
            questionCount: form.questionCount,
            difficulty: form.difficulty,
            types: form.types,
            topic: form.topic,
          },
        }),
      });
      const json = await res.json().catch(() => ({}));
      if (res.status === 503 && json.needsConfiguration) {
        setNeedsConfig(true);
        setError(json.error ?? "AI paper generation is not configured on this server.");
        return;
      }
      if (!res.ok || !json.ok) {
        setError(json.error ?? "Could not generate a paper. Try again.");
        return;
      }
      setPaper(json.paper as NewTestPaper);
      setSavedId(null);
      setDirty(false);
      setShowAnswers(false);
      setWarnings((json.warnings as string[]) ?? []);
    } catch {
      setError("Network error — check your connection and try again.");
    } finally {
      setBusy(false);
    }
  }

  async function saveMaterial() {
    const problem = validate();
    if (problem) {
      setError(problem);
      return;
    }
    setSaving(true);
    setNotice(null);
    const res = await saveRecord("materials", {
      title: form.materialTitle.trim() || `${gradeLabel(form.gradeId)} ${areaName(form.learningAreaId)} notes`,
      classId: form.classId,
      gradeId: form.gradeId,
      learningAreaId: form.learningAreaId,
      termId: activeTermId,
      notes: form.notes.trim(),
    });
    setSaving(false);
    if (!res.ok) {
      setNotice({ kind: "err", text: res.error ?? "Could not save the study material." });
      return;
    }
    const created = res.item as StudyMaterial | undefined;
    if (created?.id) setForm((f) => ({ ...f, reuseId: created.id }));
    setNotice({ kind: "ok", text: "Study material saved — you can reuse it from the list below." });
  }

  function loadMaterial(m: StudyMaterial) {
    setForm((f) => ({
      ...f,
      reuseId: m.id,
      materialTitle: m.title,
      notes: m.notes,
      classId: m.classId,
      gradeId: m.gradeId,
      learningAreaId: m.learningAreaId,
    }));
    setError(null);
    setNotice({ kind: "ok", text: `Loaded “${m.title}”.` });
  }

  async function removeMaterial(m: StudyMaterial) {
    if (!confirm(`Delete the saved notes “${m.title}”?`)) return;
    const res = await deleteRecord("materials", m.id);
    setNotice(
      res.ok
        ? { kind: "ok", text: "Study material deleted." }
        : { kind: "err", text: res.error ?? "Could not delete." },
    );
    if (res.ok && form.reuseId === m.id) setForm((f) => ({ ...f, reuseId: "" }));
  }

  function patchPaper(patch: Partial<NewTestPaper>) {
    setPaper((p) => (p ? { ...p, ...patch } : p));
    setDirty(true);
  }

  function patchAnswer(number: number, value: string) {
    setPaper((p) =>
      p
        ? {
            ...p,
            questions: p.questions.map((q) => (q.number === number ? { ...q, answer: value } : q)),
          }
        : p,
    );
    setDirty(true);
  }

  async function savePaper() {
    if (!paper) return;
    setSaving(true);
    setNotice(null);
    const res = await saveRecord(
      "papers",
      paper as unknown as Record<string, unknown>,
      savedId ?? undefined,
    );
    setSaving(false);
    if (!res.ok) {
      setNotice({ kind: "err", text: res.error ?? "Could not save the paper." });
      return;
    }
    const created = res.item as { id?: string } | undefined;
    setSavedId(created?.id ?? savedId);
    setDirty(false);
    setNotice({ kind: "ok", text: "Paper saved to this workspace." });
  }

  function openPaper(p: TestPaper) {
    setPaper(toDraft(p));
    setSavedId(p.id);
    setDirty(false);
    setWarnings([]);
    setError(null);
    setShowAnswers(false);
    setNotice(null);
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  async function removePaper(p: TestPaper) {
    if (!confirm(`Delete the paper “${p.title}”?`)) return;
    const res = await deleteRecord("papers", p.id);
    if (!res.ok) {
      setNotice({ kind: "err", text: res.error ?? "Could not delete the paper." });
      return;
    }
    if (savedId === p.id) {
      setSavedId(null);
      setDirty(false);
    }
    setNotice({ kind: "ok", text: "Paper deleted." });
  }

  /* --------------------------------- render --------------------------------- */

  const termLabel =
    data.terms.find((t) => t.id === activeTermId)?.label ?? "Term";
  const groups = paper ? groupQuestions(paper.questions) : [];

  return (
    <div>
      <div className="no-print">
        <SectionHeader
          title="Test Papers"
          hint="Paste the notes you taught, choose the shape of the paper, and let AI draft a question paper with a marking guide for you to review."
        />
      </div>

      {notice ? (
        <div className="mb-4 no-print">
          <CbcNotice kind={notice.kind}>{notice.text}</CbcNotice>
        </div>
      ) : null}

      <div className="grid gap-5 lg:grid-cols-2">
        {/* ------------------------------ composer ------------------------------ */}
        <div className="space-y-5 no-print">
          <form onSubmit={generate} className="cbc-card">
            <h2 className="font-heading text-base font-bold text-ink-900">
              1 · Study material
            </h2>
            <p className="mt-1 text-sm text-ink-500">
              Only what you paste here is used — the paper never tests content that is not in your
              notes.
            </p>

            <div className="mt-4 grid gap-3 sm:grid-cols-2">
              <CbcField label="Notes title" hint="Shown in the saved list">
                <CbcInput
                  value={form.materialTitle}
                  onChange={(e) => setForm((f) => ({ ...f, materialTitle: e.target.value }))}
                  placeholder="e.g. Water conservation notes"
                />
              </CbcField>
              <CbcField label="Reuse saved notes">
                <CbcSelect
                  value={form.reuseId}
                  onChange={(e) => {
                    const m = savedMaterials.find((x) => x.id === e.target.value);
                    if (m) loadMaterial(m);
                    else setForm((f) => ({ ...f, reuseId: "" }));
                  }}
                >
                  <option value="">Start fresh</option>
                  {savedMaterials.map((m) => (
                    <option key={m.id} value={m.id}>
                      {m.title}
                    </option>
                  ))}
                </CbcSelect>
              </CbcField>
            </div>

            <div className="mt-3">
              <CbcField
                label="Paste the study material"
                hint={`${form.notes.trim().length} / ${MAX_MATERIAL_CHARS} characters · minimum ${MIN_MATERIAL_CHARS}`}
              >
                <CbcTextarea
                  rows={8}
                  value={form.notes}
                  onChange={(e) => setForm((f) => ({ ...f, notes: e.target.value, reuseId: "" }))}
                  placeholder={"Paste the notes, textbook extract or topic summary you taught — e.g.\n\nWater conservation means using water carefully so that it is not wasted. In school we close taps after use, repair leaking pipes and collect rain water in tanks…"}
                />
              </CbcField>
            </div>

            <div className="mt-3 flex flex-wrap items-center gap-2">
              <CbcButton
                type="button"
                variant="ghost"
                onClick={() => void saveMaterial()}
                disabled={saving || !form.notes.trim()}
              >
                Save these notes
              </CbcButton>
              <span className="text-xs text-ink-500">Saved notes can be reused for other papers.</span>
            </div>

            <h2 className="mt-6 font-heading text-base font-bold text-ink-900">
              2 · Paper settings
            </h2>

            <div className="mt-3 grid gap-3 sm:grid-cols-2">
              <CbcField label="Class" hint="Leave blank to write for a grade instead">
                <CbcSelect value={form.classId} onChange={(e) => setClass(e.target.value)}>
                  <option value="">No class — choose a grade</option>
                  {classesSorted.map((c) => (
                    <option key={c.id} value={c.id}>
                      {c.name} · {gradeLabel(c.gradeId)}
                    </option>
                  ))}
                </CbcSelect>
              </CbcField>
              <CbcField label="Grade" hint={form.classId ? "Taken from the class" : undefined}>
                <CbcSelect
                  value={form.gradeId}
                  onChange={(e) => setGrade(e.target.value)}
                  disabled={!!form.classId}
                >
                  <option value="">Select grade…</option>
                  {CURRICULUM_SEED.map((g) => (
                    <option key={g.id} value={g.id}>
                      {g.label}
                    </option>
                  ))}
                </CbcSelect>
              </CbcField>

              <CbcField label="Learning area">
                <CbcSelect
                  value={form.learningAreaId}
                  onChange={(e) => setForm((f) => ({ ...f, learningAreaId: e.target.value }))}
                >
                  <option value="">Select learning area…</option>
                  {areas.map((a) => (
                    <option key={a.id} value={a.id}>
                      {a.name}
                    </option>
                  ))}
                </CbcSelect>
              </CbcField>
              <CbcField label="Paper type">
                <CbcSelect
                  value={form.kind}
                  onChange={(e) => setForm((f) => ({ ...f, kind: e.target.value as PaperKind }))}
                >
                  {PAPER_KINDS.map((k) => (
                    <option key={k.id} value={k.id}>
                      {k.label}
                    </option>
                  ))}
                </CbcSelect>
              </CbcField>

              <CbcField label="Paper title" hint="Leave blank for a suggested title">
                <CbcInput
                  value={form.title}
                  onChange={(e) => setForm((f) => ({ ...f, title: e.target.value }))}
                  placeholder="e.g. End of term assessment"
                />
              </CbcField>
              <CbcField label="Focus (optional)" hint="Narrow the paper to one topic">
                <CbcInput
                  value={form.topic}
                  onChange={(e) => setForm((f) => ({ ...f, topic: e.target.value }))}
                  placeholder="e.g. water conservation"
                />
              </CbcField>

              <CbcField label="Questions">
                <CbcInput
                  type="number"
                  min={3}
                  max={40}
                  value={form.questionCount}
                  onChange={(e) => setForm((f) => ({ ...f, questionCount: Number(e.target.value) }))}
                />
              </CbcField>
              <CbcField label="Total marks">
                <CbcInput
                  type="number"
                  min={10}
                  max={200}
                  value={form.totalMarks}
                  onChange={(e) => setForm((f) => ({ ...f, totalMarks: Number(e.target.value) }))}
                />
              </CbcField>
              <CbcField label="Minutes">
                <CbcInput
                  type="number"
                  min={5}
                  max={240}
                  value={form.durationMins}
                  onChange={(e) => setForm((f) => ({ ...f, durationMins: Number(e.target.value) }))}
                />
              </CbcField>
              <CbcField label="Level">
                <CbcSelect
                  value={form.difficulty}
                  onChange={(e) =>
                    setForm((f) => ({ ...f, difficulty: e.target.value as PaperDifficulty }))
                  }
                >
                  {PAPER_DIFFICULTIES.map((d) => (
                    <option key={d.id} value={d.id}>
                      {d.label}
                    </option>
                  ))}
                </CbcSelect>
              </CbcField>
            </div>

            <fieldset className="mt-4">
              <legend className="text-[13px] font-semibold text-ink-900">Question types</legend>
              <div className="mt-2 flex flex-wrap gap-1.5">
                {QUESTION_TYPES.map((t) => {
                  const on = form.types.includes(t.id);
                  return (
                    <button
                      key={t.id}
                      type="button"
                      aria-pressed={on}
                      title={t.hint}
                      onClick={() => toggleType(t.id)}
                      className={`rounded-full border px-3 py-1.5 text-xs font-semibold transition-colors ${
                        on
                          ? "border-maroon-700 bg-maroon-700 text-white"
                          : "border-ink-200 bg-white text-ink-600 hover:border-maroon-300"
                      }`}
                    >
                      {t.label}
                    </button>
                  );
                })}
              </div>
            </fieldset>

            {error ? (
              <div className="mt-4">
                <CbcNotice kind="err">{error}</CbcNotice>
                {needsConfig ? (
                  <p className="mt-2 text-xs leading-relaxed text-ink-500">
                    To enable AI paper generation, add{" "}
                    <code className="rounded bg-ink-100 px-1">AI_API_KEY</code> (and optionally{" "}
                    <code className="rounded bg-ink-100 px-1">AI_BASE_URL</code> /{" "}
                    <code className="rounded bg-ink-100 px-1">AI_MODEL</code>) to{" "}
                    <code className="rounded bg-ink-100 px-1">.env.local</code> and restart the
                    server.
                  </p>
                ) : null}
              </div>
            ) : null}

            <div className="mt-4 flex flex-wrap items-center gap-3">
              <CbcButton type="submit" disabled={busy}>
                {busy ? "Drafting your paper…" : paper ? "Generate again" : "Generate test paper"}
              </CbcButton>
              {busy ? (
                <span className="text-xs text-ink-500" role="status">
                  Writing questions from your notes — this can take up to a minute.
                </span>
              ) : (
                <span className="text-xs text-ink-500">
                  Signed in as {me.fullName} · review every question before use.
                </span>
              )}
            </div>
          </form>

          {/* Saved papers */}
          <div className="cbc-card">
            <h2 className="font-heading text-base font-bold text-ink-900">
              Saved papers ({savedPapers.length})
            </h2>
            {savedPapers.length ? (
              <ul className="mt-3 space-y-2">
                {savedPapers.map((p) => (
                  <li
                    key={p.id}
                    className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-ink-100 bg-white px-3 py-2.5"
                  >
                    <div className="min-w-0">
                      <p className="truncate text-sm font-semibold text-ink-900">
                        {p.title}{" "}
                        {savedId === p.id ? <CbcBadge tone="blue">open</CbcBadge> : null}
                      </p>
                      <p className="text-xs text-ink-500">
                        {gradeLabel(p.gradeId)} · {areaName(p.learningAreaId)} ·{" "}
                        {p.questions.length} questions · {p.totalMarks} marks ·{" "}
                        {fmtDate(p.updatedAt)}
                      </p>
                    </div>
                    <div className="flex gap-2">
                      <CbcButton type="button" variant="ghost" onClick={() => openPaper(p)}>
                        Open
                      </CbcButton>
                      <CbcButton type="button" variant="danger" onClick={() => void removePaper(p)}>
                        Delete
                      </CbcButton>
                    </div>
                  </li>
                ))}
              </ul>
            ) : (
              <CbcEmpty
                title="No papers saved yet"
                hint="Generate a paper from your study material, review it, then save it here."
              />
            )}
          </div>

          {savedMaterials.length ? (
            <div className="cbc-card">
              <h2 className="font-heading text-base font-bold text-ink-900">
                Saved study material ({savedMaterials.length})
              </h2>
              <ul className="mt-3 space-y-2">
                {savedMaterials.map((m) => (
                  <li
                    key={m.id}
                    className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-ink-100 bg-white px-3 py-2.5"
                  >
                    <div className="min-w-0">
                      <p className="truncate text-sm font-semibold text-ink-900">{m.title}</p>
                      <p className="text-xs text-ink-500">
                        {gradeLabel(m.gradeId)} · {areaName(m.learningAreaId)} ·{" "}
                        {m.notes.length} characters · {fmtDate(m.updatedAt)}
                      </p>
                    </div>
                    <div className="flex gap-2">
                      <CbcButton type="button" variant="ghost" onClick={() => loadMaterial(m)}>
                        Use
                      </CbcButton>
                      <CbcButton
                        type="button"
                        variant="danger"
                        onClick={() => void removeMaterial(m)}
                      >
                        Delete
                      </CbcButton>
                    </div>
                  </li>
                ))}
              </ul>
            </div>
          ) : null}
        </div>

        {/* ------------------------------- preview ------------------------------ */}
        <div>
          {paper ? (
            <>
              {warnings.length ? (
                <div className="mb-3 space-y-2 no-print">
                  {warnings.map((w) => (
                    <CbcNotice key={w} kind="info">
                      {w}
                    </CbcNotice>
                  ))}
                </div>
              ) : null}

              <div className="mb-3 rounded-xl border border-cbc-line bg-white p-3 no-print">
                <div className="grid gap-3 sm:grid-cols-2">
                  <CbcField label="Paper title">
                    <CbcInput
                      value={paper.title}
                      onChange={(e) => patchPaper({ title: e.target.value })}
                    />
                  </CbcField>
                  <CbcField label="Instructions to learners">
                    <CbcTextarea
                      rows={2}
                      value={paper.instructions}
                      onChange={(e) => patchPaper({ instructions: e.target.value })}
                    />
                  </CbcField>
                </div>
                <div className="mt-3 flex flex-wrap items-center gap-3">
                  <label className="flex items-center gap-2 text-sm font-semibold text-ink-700">
                    <input
                      type="checkbox"
                      checked={showAnswers}
                      onChange={(e) => setShowAnswers(e.target.checked)}
                      className="h-4 w-4 accent-[#8e2031]"
                    />
                    Show marking guide
                  </label>
                  <CbcButton type="button" variant="ghost" onClick={() => window.print()}>
                    Print / PDF
                  </CbcButton>
                  <CbcButton
                    type="button"
                    onClick={() => void savePaper()}
                    disabled={saving || (savedId !== null && !dirty)}
                  >
                    {saving ? "Saving…" : savedId && !dirty ? "Saved ✓" : savedId ? "Save changes" : "Save paper"}
                  </CbcButton>
                  <CbcButton
                    type="button"
                    variant="ghost"
                    onClick={() => {
                      setPaper(null);
                      setSavedId(null);
                      setDirty(false);
                      setWarnings([]);
                    }}
                  >
                    New paper
                  </CbcButton>
                </div>
                <p className="mt-2 text-xs text-ink-500">
                  Marking guides stay on screen — printing always produces the copy learners sit.
                </p>
              </div>

              <article className="cbc-card paper-sheet">
                <header className="border-b-2 border-ink-900 pb-3 text-center">
                  <p className="font-heading text-lg font-bold uppercase tracking-wide text-ink-900">
                    Mainflow School
                  </p>
                  <p className="text-[11px] uppercase tracking-[0.25em] text-ink-500">
                    {KIND_LABEL[paper.kind]} paper
                  </p>
                  <h2 className="mt-2 font-heading text-xl font-bold text-ink-900">
                    {paper.title}
                  </h2>
                  <p className="mt-1 text-sm text-ink-700">
                    {gradeLabel(paper.gradeId)} · {areaName(paper.learningAreaId)}
                    {paper.classId ? ` · ${classLabel(data.classes, paper.classId)}` : ""} ·{" "}
                    {termLabel}
                  </p>
                  <div className="mt-2 flex flex-wrap justify-center gap-x-5 gap-y-1 text-xs font-semibold uppercase tracking-wide text-ink-600">
                    <span>Time: {paper.durationMins} minutes</span>
                    <span>Marks: {paper.totalMarks}</span>
                    <span>Questions: {paper.questions.length}</span>
                    <span>Level: {DIFFICULTY_LABEL[paper.difficulty]}</span>
                  </div>
                </header>

                <p className="mt-3 whitespace-pre-wrap rounded-lg bg-ink-50 px-3 py-2 text-sm leading-relaxed text-ink-700">
                  {paper.instructions}
                </p>

                <div className="mt-4 space-y-5">
                  {groups.map((group, gi) => {
                    const letter = String.fromCharCode(65 + gi);
                    const sectionMarks = group.questions.reduce((s, q) => s + q.marks, 0);
                    const each = group.questions[0]?.marks ?? 0;
                    const uniform = group.questions.every((q) => q.marks === each);
                    const sectionMeta = uniform
                      ? `${group.questions.length} × ${each} mark${each === 1 ? "" : "s"}`
                      : `${group.questions.length} questions · ${sectionMarks} marks`;
                    return (
                      <section key={`${letter}-${group.type}`}>
                        <h3 className="font-heading text-sm font-bold uppercase tracking-wide text-maroon-800">
                          Section {letter} — {TYPE_LABEL[group.type]}{" "}
                          <span className="font-normal normal-case tracking-normal text-ink-500">
                            ({sectionMeta})
                          </span>
                        </h3>
                        <ol className="mt-2 space-y-3">
                          {group.questions.map((q) => (
                            <li key={q.number} className="paper-question text-sm">
                              <div className="flex items-start gap-2">
                                <span className="min-w-[1.6rem] shrink-0 font-bold tabular-nums text-ink-900">
                                  {q.number}.
                                </span>
                                <div className="min-w-0 flex-1">
                                  <p className="whitespace-pre-wrap leading-relaxed text-ink-800">
                                    {q.text}{" "}
                                    <span className="whitespace-nowrap text-xs font-semibold text-ink-500">
                                      [{q.marks} {q.marks === 1 ? "mark" : "marks"}]
                                    </span>
                                  </p>
                                  {q.options?.length ? (
                                    <ul className="mt-1.5 grid gap-1 sm:grid-cols-2">
                                      {q.options.map((opt, i) => (
                                        <li key={`${q.number}-${i}`} className="flex gap-2">
                                          <span className="font-semibold text-ink-600">
                                            {"abcd"[i] ?? `${i + 1}.`}
                                          </span>
                                          <span className="text-ink-800">{opt}</span>
                                        </li>
                                      ))}
                                    </ul>
                                  ) : null}
                                  {q.type === "truefalse" && !q.options?.length ? (
                                    <p className="mt-1 text-xs text-ink-500">
                                      (  ) True &nbsp;&nbsp; (  ) False
                                    </p>
                                  ) : null}
                                  {showAnswers ? (
                                    <div className="mt-1.5 rounded-lg border border-dashed border-ink-300 bg-ink-50 px-3 py-2 no-print">
                                      <label className="block text-[11px] font-bold uppercase tracking-wide text-ink-500">
                                        Marking guide · question {q.number}
                                      </label>
                                      <CbcTextarea
                                        rows={2}
                                        value={q.answer}
                                        placeholder="Expected answer / points to award"
                                        onChange={(e) => patchAnswer(q.number, e.target.value)}
                                      />
                                    </div>
                                  ) : null}
                                </div>
                              </div>
                            </li>
                          ))}
                        </ol>
                      </section>
                    );
                  })}
                </div>

                <footer className="mt-6 border-t border-ink-200 pt-3 text-center text-xs text-ink-500">
                  {paper.materialTitle ? `Based on: ${paper.materialTitle} · ` : ""}
                  {paper.model ? `Drafted with ${paper.model} · ` : ""}
                  End of paper — check against official KICD curriculum designs before use.
                </footer>
              </article>
            </>
          ) : (
            <div className="cbc-card">
              <CbcEmpty
                title="No paper yet"
                hint="Paste your study material on the left, choose the grade and paper settings, then generate. You review and save the result — nothing is stored automatically."
              />
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
